def test_the_baseline_cli_needs_no_experimental_flag(tmp_path,
                                                     monkeypatch) -> None:
    """`run_cover.py --config <baseline>` and nothing else."""
    import importlib.util

    path = SCRIPTS / "run_cover.py"
    sys.path.insert(0, str(SCRIPTS))
    try:
        spec = importlib.util.spec_from_file_location("run_cover_restored", path)
        runner = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(runner)
    finally:
        sys.path.remove(str(SCRIPTS))

    built: list[str] = []

    class _Built(RuntimeError):
        pass

    def stub(block):
        built.append(block["model_id"])
        raise _Built("reached build_runtime")

    monkeypatch.setattr(runner, "build_runtime", stub)
    monkeypatch.setattr(runner, "require_huggingface_runtime",
                        lambda *a, **k: None)
    monkeypatch.setattr(sys, "argv", [
        "run_cover.py", "--config", str(EXPERIMENTS / "cover_kbc_v2_test.yaml")])
    with pytest.raises(_Built):
        runner.main()
    assert built == [BASELINE_ENUMERATOR]
