def _load(name: str) -> dict:
    return yaml.safe_load((EXPERIMENTS / name).read_text())


def _executable_source(path) -> str:
    """A module's code with docstrings removed.

    Scanned rather than raw text because this repository documents what it
    deliberately does *not* do - and after a retirement it documents what it
    used to. A prose scan would flag the record of the removal as the thing.
    """
    tree = ast.parse(path.read_text())
    for node in ast.walk(tree):
        if not isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef,
                                 ast.AsyncFunctionDef)):
            continue
        body = getattr(node, "body", [])
        if (body and isinstance(body[0], ast.Expr)
                and isinstance(body[0].value, ast.Constant)
                and isinstance(body[0].value.value, str)):
            node.body = body[1:] or [ast.Pass()]
    return ast.unparse(tree)


